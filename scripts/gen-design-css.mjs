// Compiles the design system's stylesheet for the Claude Design converter
// (`/design-sync`, `cfg.cssEntry`) — the CSS every design built with the
// system will load.
//
// The repo ships no compiled CSS of its own: `globals.css` is Tailwind v4
// source, and the only compiled output is the docs site's hashed chunk in
// `out/`. This compiles the same thing deterministically, at a stable path:
//
//   1. Tailwind is compiled from `globals.css` against every class name the
//      repo's own source uses (primitives, demos, docs shell) — the vocabulary
//      the design agent may reuse for its own layout, with the same scanner
//      the CLI uses. Unlike the card stylesheet (lib/base-css.mjs) nothing is
//      resolved away: designs compose utilities dynamically, so `--tw-*`
//      composition has to keep working.
//   2. The Edgecom `:root` / `.dark` blocks — plus the `@theme inline` scales
//      Tailwind never emits as variables — are moved to the very top, so the
//      platform's token manifest reads Edgecom's tokens before anything else.
//   3. Docs-site-only rules (Shiki code blocks) are dropped.
//
// Output: .design-sync/.cache/styles.css (git-ignored; regenerated by the sync).

import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import { compile } from "@tailwindcss/node"
import postcss from "postcss"

import { readBlocks } from "./lib/tokens.mjs"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const outFile = resolve(root, ".design-sync/.cache/styles.css")

// @tailwindcss/oxide is @tailwindcss/node's own dependency; resolve it from there.
const { Scanner } = createRequire(createRequire(import.meta.url).resolve("@tailwindcss/node"))("@tailwindcss/oxide")

const globalsCss = readFileSync(resolve(root, "src/app/globals.css"), "utf8")
const { light, theme } = readBlocks(globalsCss)

const scanner = new Scanner({ sources: [{ base: resolve(root, "src"), pattern: "**/*.{ts,tsx,mdx,md,html}", negated: false }] })
const candidates = scanner.scan()

const compiler = await compile(globalsCss, { base: resolve(root, "src/app"), onDependency: () => {} })
const css = postcss.parse(compiler.build(candidates))

// Edgecom's @theme inline tokens that are tokens in their own right (type,
// radius, motion scales) — not the `--color-x: var(--x)` utility aliases.
let rootRule = null
css.each((n) => {
  if (n.type === "rule" && n.selector === ":root" && !rootRule) rootRule = n
})
if (!rootRule) throw new Error("globals.css has no top-level :root block")
const declared = new Set()
rootRule.walkDecls((d) => declared.add(d.prop))
for (const [name, value] of Object.entries(theme)) {
  const alias = value.match(/^var\(--([\w-]+)\)$/)
  if (alias && (alias[1] in light || alias[1] in theme)) continue
  if (!declared.has(`--${name}`)) rootRule.append({ prop: `--${name}`, value })
}

// Tokens first; docs-site cruft out.
const lead = []
css.each((n) => {
  if (n.type === "rule" && (n.selector === ":root" || n.selector === ".dark")) lead.push(n)
})
for (const n of lead) n.remove()
css.prepend(...lead.sort((a, b) => (a.selector === ":root" ? -1 : b.selector === ":root" ? 1 : 0)))
css.walkRules((r) => {
  if (r.selector.includes(".shiki")) r.remove()
})

let utilities = 0
css.walkAtRules("layer", (l) => {
  if (l.params.trim() === "utilities") l.each((n) => n.type === "rule" && utilities++)
})

const banner =
  `/* Generated by scripts/gen-design-css.mjs from src/app/globals.css — do not hand-edit.\n` +
  `   Edgecom tokens first (:root light, .dark overrides), then Tailwind compiled against every\n` +
  `   class the repo's own source uses. This is the stylesheet designs built with the system load. */\n`
mkdirSync(dirname(outFile), { recursive: true })
const out = banner + css.toString().trim() + "\n"
writeFileSync(outFile, out)
console.log(
  `gen-design-css — ${(out.length / 1024).toFixed(0)} KB, ${utilities} utilities from ${candidates.length} candidates, ` +
    `${lead.reduce((n, r) => n + r.nodes.length, 0)} token declarations → .design-sync/.cache/styles.css`,
)
